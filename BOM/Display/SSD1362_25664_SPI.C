//=========================================	50%画面显示函数
void White_IMAGE2(unsigned char dat1,unsigned char dat2)
{
	unsigned int x,y,z;

	Write_command(0X15); //Set column Address
	Write_command(0X00); //Start column Address
	Write_command(0X7F); //End column Address

	Write_command(0X75); //Set Row Address
	Write_command(0X00); //Start Row Address
	Write_command(0X3F); //End Row Address
	
	for(y = 0;y < 32;y ++)
	{
		for(z=0;z<2;z++)
		{
    		for(x = 0;x < 32;x ++)
			{
				Write_data(dat1);
			}
			for(x = 0;x < 32;x ++)
			{
				Write_data(dat2);
			}		
		}  
	}
	for(y = 0;y < 32;y ++)
	{
		for(z=0;z<2;z++)
		{
    		for(x = 0;x < 32;x ++)
			{
				Write_data(~dat1);
			}
			for(x = 0;x < 32;x ++)
			{
				Write_data(~dat2);
			}		
		}  
	}
}

